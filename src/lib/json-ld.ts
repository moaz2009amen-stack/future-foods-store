// بنستبدل أي "<" بصيغتها المرمّزة \u003c قبل حقن الـ JSON جوه <script>.
// السبب: لو أي حقل نصي (اسم منتج، وصف، اسم ماركت) احتوى بالصدفة أو
// بسوء نية على "</script>"، ده ممكن يقفل الـ script tag بدري ويسمح
// بحقن HTML/JS تعسفي في الصفحة. الاستبدال ده بيمنع الاحتمال ده تماماً
// من غير ما يأثر على شكل البيانات نفسها لمحركات البحث.
export function safeJsonLd(data: unknown): string {
  return JSON.stringify(data).replace(/</g, "\\u003c");
}